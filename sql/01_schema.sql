CREATE TABLE ems_departments (
  department_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name VARCHAR2(100) NOT NULL,
  location        VARCHAR2(100),
  created_on      DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT ems_departments_name_uk UNIQUE (department_name)
);

CREATE TABLE ems_employees (
  employee_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name    VARCHAR2(50)  NOT NULL,
  last_name     VARCHAR2(50)  NOT NULL,
  email         VARCHAR2(150) NOT NULL,
  phone         VARCHAR2(30),
  department_id NUMBER        NOT NULL,
  job_title     VARCHAR2(100) NOT NULL,
  hire_date     DATE          DEFAULT TRUNC(SYSDATE) NOT NULL,
  salary        NUMBER(12,2)  NOT NULL,
  status        VARCHAR2(20)  DEFAULT 'Active' NOT NULL,
  manager_id    NUMBER,
  created_on    DATE DEFAULT SYSDATE NOT NULL,
  updated_on    DATE,
  CONSTRAINT ems_employees_email_uk  UNIQUE (email),
  CONSTRAINT ems_employees_dept_fk   FOREIGN KEY (department_id) REFERENCES ems_departments (department_id),
  CONSTRAINT ems_employees_mgr_fk    FOREIGN KEY (manager_id) REFERENCES ems_employees (employee_id),
  CONSTRAINT ems_employees_salary_ck CHECK (salary >= 0),
  CONSTRAINT ems_employees_status_ck CHECK (status IN ('Active', 'On leave', 'Terminated'))
);

CREATE INDEX ems_employees_dept_ix ON ems_employees (department_id);
CREATE INDEX ems_employees_status_ix ON ems_employees (status);

-- Audit trail for salary changes
CREATE TABLE ems_salary_history (
  history_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id  NUMBER       NOT NULL REFERENCES ems_employees (employee_id),
  old_salary   NUMBER(12,2),
  new_salary   NUMBER(12,2) NOT NULL,
  changed_on   DATE DEFAULT SYSDATE NOT NULL,
  changed_by   VARCHAR2(100) DEFAULT COALESCE(SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER)
);

-- Keep UPDATED_ON current and log salary changes
CREATE OR REPLACE TRIGGER ems_employees_biu
  BEFORE INSERT OR UPDATE ON ems_employees
  FOR EACH ROW
BEGIN
  :NEW.email := LOWER(TRIM(:NEW.email));
  IF UPDATING THEN
    :NEW.updated_on := SYSDATE;
  END IF;
END;
/

CREATE OR REPLACE TRIGGER ems_employees_salary_aiu
  AFTER INSERT OR UPDATE OF salary ON ems_employees
  FOR EACH ROW
BEGIN
  IF INSERTING OR :OLD.salary <> :NEW.salary THEN
    INSERT INTO ems_salary_history (employee_id, old_salary, new_salary)
    VALUES (:NEW.employee_id, :OLD.salary, :NEW.salary);
  END IF;
END;
/

-- Reporting view used by the dashboard / interactive report
CREATE OR REPLACE VIEW ems_employee_v AS
SELECT e.employee_id,
       e.first_name || ' ' || e.last_name AS full_name,
       e.email,
       d.department_name,
       e.job_title,
       e.hire_date,
       e.salary,
       e.status,
       ROUND(MONTHS_BETWEEN(SYSDATE, e.hire_date) / 12, 1) AS years_of_service,
       m.first_name || ' ' || m.last_name AS manager_name
  FROM ems_employees e
  JOIN ems_departments d ON d.department_id = e.department_id
  LEFT JOIN ems_employees m ON m.employee_id = e.manager_id;
